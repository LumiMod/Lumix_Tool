export function translate(lang, key, params) {
  const dict = MESSAGES[lang] || MESSAGES.zh;
  let text = dict[key] ?? MESSAGES.zh[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replaceAll(`{${k}}`, String(v));
    }
  }
  return text;
}

const I18nContext = createContext({
  lang: 'zh',
  setLang: () => {},
  needsLanguageChoice: false,
  t: (key, params) => translate('zh', key, params),
});

export function I18nProvider({ children, initialLang = null }) {
  const stored = initialLang || getStoredLanguage();
  const [lang, setLangState] = useState(stored || 'zh');
  const [needsLanguageChoice, setNeedsLanguageChoice] = useState(() => {
    if (initialLang) return false;
    return typeof localStorage !== 'undefined' && getStoredLanguage() === null;
  });

  const setLang = useCallback(code => {
    if (!SUPPORTED.has(code)) return;
    setLangState(code);
    saveLanguage(code);
    setNeedsLanguageChoice(false);
  }, []);

  const t = useCallback((key, params) => translate(lang, key, params), [lang]);

  const value = useMemo(
    () => ({ lang, setLang, needsLanguageChoice, t }),
    [lang, setLang, needsLanguageChoice, t],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}
